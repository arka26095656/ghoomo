-- Works on both PostgreSQL and H2 (PostgreSQL mode)

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    name           VARCHAR(120) NOT NULL,
    home_city      VARCHAR(120),
    travel_style   VARCHAR(40),
    budget_inr     INTEGER,
    interests      VARCHAR(500),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE itineraries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title          VARCHAR(200) NOT NULL,
    destination    VARCHAR(200) NOT NULL,
    start_date     DATE,
    day_count      INTEGER NOT NULL,
    budget_inr     INTEGER,
    estimated_inr  INTEGER,
    plan_json      VARCHAR(200000) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_itineraries_user ON itineraries(user_id);

CREATE TABLE chat_sessions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title          VARCHAR(200) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_sessions_user ON chat_sessions(user_id);

CREATE TABLE chat_messages (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id     BIGINT NOT NULL REFERENCES chat_sessions(id) ON DELETE CASCADE,
    role           VARCHAR(20) NOT NULL,
    content        VARCHAR(20000) NOT NULL,
    itinerary_id   BIGINT REFERENCES itineraries(id) ON DELETE SET NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_messages_session ON chat_messages(session_id);
